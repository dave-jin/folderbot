/**
 * 마크다운 → 한 줄 평문 — 알림 미리보기용 (2026-09-25 디자인 검수).
 *
 * 🔴 알림 목록·폰 푸시·맥 알림·「마지막 결과」 타일이 답의 **원문**을 잘라 보여 줘서
 *    `## 증상 정리 **증상**: …` 처럼 기호가 그대로 나왔다. 사람이 읽는 자리에는 글자만 남긴다.
 * ⚠ 뜻이 있는 글자는 지우지 않는다 — 링크는 글만, 코드는 안의 글자는 남기고 백틱만 뗀다.
 */
export function mdPlain(md: string): string {
  return md
    .replace(/```[^\n]*\n?/g, ' ')                       // 펜스 줄(언어 이름 포함)
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')            // 그림 → 대체 글
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')             // 링크 → 글
    .replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_m, a: string, b?: string) => b ?? a)   // 위키링크
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')                  // 제목 표시
    .replace(/^\s{0,3}>\s?(\[![a-z]+\]\s?)?/gim, '')      // 인용·콜아웃
    .replace(/^\s*(?:[-*+]|\d+[.)])\s+(\[[ xX]\]\s+)?/gm, '')   // 목록 머리·체크박스
    .replace(/^\s*([-*_])(\s*\1){2,}\s*$/gm, ' ')        // 가로줄
    .replace(/^\s*\|?(\s*:?-{3,}:?\s*\|)+\s*:?-*:?\s*$/gm, ' ')   // 표 구분 줄
    .replace(/\|/g, ' ')
    .replace(/(\*\*|__)(.+?)\1/g, '$2')                  // 굵게
    .replace(/(^|[^\p{L}\p{N}*_])[*_]([^*_\n]+)[*_](?=[^\p{L}\p{N}*_]|$)/gu, '$1$2')   // 기울임 — ⚠ 한글도 «글자» 로 쳐야 `제품_Rondo … 01_기획` 이 기울임으로 안 먹힌다
    .replace(/~~(.+?)~~/g, '$1')
    .replace(/`([^`\n]+)`/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
}
